import { createClient } from "https://esm.sh/@supabase/supabase-js@2";

const SITE_URL = "https://bschoolbuzz.com";
const DEFAULT_PRIORITY = 0.80;

const escapeXml = (value: string) => value
  .replaceAll("&", "&amp;")
  .replaceAll("<", "&lt;")
  .replaceAll(">", "&gt;")
  .replaceAll('"', "&quot;")
  .replaceAll("'", "&apos;");

const formatLastmod = (date = new Date()) => date.toISOString().replace(/\.\d{3}Z$/, "+00:00");

const buildSitemapXml = (entries: { loc: string; priority: number }[]) => {
  const lastmod = formatLastmod();
  const uniqueEntries = Array.from(
    new Map(entries.filter((e) => e.loc).map((e) => [e.loc, e])).values(),
  );

  return `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9"
        xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance"
        xsi:schemaLocation="http://www.sitemaps.org/schemas/sitemap/0.9
                            http://www.sitemaps.org/schemas/sitemap/0.9/sitemap.xsd">
<!-- Generated by BSchoolBuzz sitemap engine -->
${uniqueEntries.map((e) => `  <url>
    <loc>${escapeXml(`${SITE_URL}${e.loc}`)}</loc>
    <lastmod>${lastmod}</lastmod>
    <priority>${e.priority.toFixed(2)}</priority>
  </url>`).join("\n")}
</urlset>`;
};

Deno.serve(async () => {
  try {
    const supabaseUrl = Deno.env.get("SUPABASE_URL")!;
    const supabaseKey = Deno.env.get("SUPABASE_SERVICE_ROLE_KEY")!;
    const supabase = createClient(supabaseUrl, supabaseKey);

    // Always generate fresh from DB to avoid stale cached sitemaps
    // (saved sitemap was causing missing institute/college URLs after edits)
    const STATIC_PAGES = [
      { loc: "/", priority: 1.0 },
      { loc: "/blog", priority: DEFAULT_PRIORITY },
      { loc: "/colleges", priority: DEFAULT_PRIORITY },
      { loc: "/coaching", priority: DEFAULT_PRIORITY },
      { loc: "/about", priority: DEFAULT_PRIORITY },
      { loc: "/contact", priority: DEFAULT_PRIORITY },
      { loc: "/compare", priority: DEFAULT_PRIORITY },
      { loc: "/college-finder", priority: DEFAULT_PRIORITY },
      { loc: "/profile-analyzer", priority: DEFAULT_PRIORITY },
      { loc: "/college-shortlister", priority: DEFAULT_PRIORITY },
    ];

    const [
      { data: institutes },
      { data: colleges },
      { data: exams },
      { data: categories },
      { data: articles },
      { data: cityPages },
    ] = await Promise.all([
      supabase.from("institutes").select("slug"),
      supabase.from("colleges").select("slug"),
      supabase.from("exams").select("slug"),
      supabase.from("categories").select("slug"),
      supabase.from("articles").select("slug").eq("published", true),
      supabase.from("city_pages").select("slug").eq("active", true),
    ]);

    // Only include canonical, indexable URLs. Filtered/query-param URLs are intentionally
    // excluded — they self-canonicalize via the page's SEOHead and dilute crawl budget.
    const urls = [
      ...STATIC_PAGES,
      ...(institutes ?? []).flatMap((i: { slug: string | null }) => i.slug ? [{ loc: `/institute/${i.slug}`, priority: DEFAULT_PRIORITY }] : []),
      ...(colleges ?? []).flatMap((c: { slug: string | null }) => c.slug ? [{ loc: `/college/${c.slug}`, priority: DEFAULT_PRIORITY }] : []),
      ...(exams ?? []).flatMap((e: { slug: string | null }) => e.slug ? [{ loc: `/exam/${e.slug}`, priority: DEFAULT_PRIORITY }] : []),
      ...(categories ?? []).flatMap((c: { slug: string | null }) => c.slug ? [{ loc: `/category/${c.slug}`, priority: DEFAULT_PRIORITY }] : []),
      ...(articles ?? []).flatMap((a: { slug: string | null }) => a.slug ? [{ loc: `/article/${a.slug}`, priority: DEFAULT_PRIORITY }] : []),
      ...(cityPages ?? []).flatMap((cp: { slug: string | null }) => cp.slug ? [{ loc: `/colleges/${cp.slug}`, priority: DEFAULT_PRIORITY }] : []),
    ];

    const xml = buildSitemapXml(urls);

    return new Response(xml, {
      headers: {
        "Content-Type": "application/xml; charset=utf-8",
        "Cache-Control": "public, max-age=300, s-maxage=300",
        "Access-Control-Allow-Origin": "*",
      },
    });
  } catch (err) {
    const message = err instanceof Error ? err.message : "Unknown error";
    return new Response(`<?xml version="1.0" encoding="UTF-8"?><error>${escapeXml(message)}</error>`, {
      status: 500,
      headers: { "Content-Type": "application/xml" },
    });
  }
});
